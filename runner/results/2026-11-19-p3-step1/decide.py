"""Apply P3 step 1's fixed rules (PLAN.md, 8408ef2) to the runner's CI output. python3 decide.py CI_DIR > DECISION.md
Rules: 1 floor margin (best family beats majority by >= 3 paired SE); 2 does the best new family beat the best of
linear and mlp16 by > 2 paired SE; 3 Q54: wisard matched (accuracy >= the more accurate of linear and mlp16 minus 2
paired SE) and leading on cost (fewer instructions per item than that family), supported if on both text and adult,
weakened if only on optdigits or none, mixed otherwise; 4 every new candidate reproduces (excluded from 1-3 if not)."""
import json, math, os, sys

NEW, OLD = ("label-gbdt", "label-knn", "label-wisard"), ("label-linear", "label-mlp16")
TASKS = ("optdigits", "text", "adult")


def paired(a, b):
    assert len(a) == len(b)
    d = [x["score"] - y["score"] for x, y in zip(a, b)]
    n, m = len(d), sum(d) / len(d)
    return m, math.sqrt(sum((x - m) ** 2 for x in d) / (n - 1) / n)


def main(ci):
    out, wis = [], {}
    out += ["# P3 step 1: decision (generated by decide.py from the CI output; rules fixed in PLAN.md before any run)", ""]
    for t in TASKS:
        dev = json.load(open(os.path.join(ci, f"dev-{t}.json")))
        rep = json.load(open(os.path.join(ci, f"reproduce-{t}.json")))
        ok = {r["candidate"] for r in rep if r.get("identical")}
        C = dev["candidates"]
        out += [f"## {t} (dev, {dev['n']} items; run {dev.get('run_id', '?')}, jail {dev.get('jail', {}).get('mode', dev.get('jail'))})", "",
                "| candidate | accuracy | SE | Ir/item | ns/item | reproduces |", "|---|---|---|---|---|---|"]
        for name, c in sorted(C.items(), key=lambda kv: -kv[1]["mean"]):
            out.append(f"| {name} | {c['mean']:.4f} | {c['se']:.4f} | {c['ir_per_item']:.0f} | {c['ns_per_item']:.0f} | {name in ok} |")
        new_ok = [n for n in NEW if n in C and n in ok]
        bad = [n for n in NEW if n in C and n not in ok]
        out.append("")
        if bad:
            out.append(f"Rule 4: did not reproduce, excluded from rules 1-3: {', '.join(bad)}.")
        else:
            out.append("Rule 4: every new candidate reproduced (identical weights twice).")
        fams = [n for n in C if n != "majority" and (n in OLD or n in new_ok)]
        best = max(fams, key=lambda n: C[n]["mean"])
        m, s = paired(C[best]["items"], C["majority"]["items"])
        out.append(f"Rule 1: best family {best} beats majority by {m:.4f} (paired SE {s:.4f}, {m / s:.1f} SE): "
                   f"{'holds' if m >= 3 * s else 'FAILS'}.")
        bo = max(OLD, key=lambda n: C[n]["mean"])
        if new_ok:
            bn = max(new_ok, key=lambda n: C[n]["mean"])
            m, s = paired(C[bn]["items"], C[bo]["items"])
            out.append(f"Rule 2: best new {bn} vs best of linear/mlp16 ({bo}): {m:+.4f} (paired SE {s:.4f}, {m / s:+.1f} SE): "
                       f"{'YES, beats it by more than 2 SE' if m > 2 * s else 'no'}.")
        if "label-wisard" in new_ok:
            w = C["label-wisard"]
            m, s = paired(w["items"], C[bo]["items"])
            matched = m >= -2 * s
            lead = matched and w["ir_per_item"] < C[bo]["ir_per_item"]
            wis[t] = lead
            out.append(f"Rule 3 (Q54): wisard vs {bo}: accuracy {m:+.4f} (paired SE {s:.4f}, {m / s:+.1f} SE) -> "
                       f"{'matched' if matched else 'not matched'}; Ir/item {w['ir_per_item']:.0f} vs {C[bo]['ir_per_item']:.0f} -> "
                       f"{'leads on cost' if lead else 'no cost lead at matched accuracy'}.")
        out.append("")
    nd = [wis.get("text"), wis.get("adult")]
    verdict = ("supported" if all(nd) else "weakened" if not any(nd) else "mixed")
    out += [f"## Q54 for lookup tables (rule 3): **{verdict}** (text: {wis.get('text')}, adult: {wis.get('adult')}, "
            f"optdigits: {wis.get('optdigits')})", ""]
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
